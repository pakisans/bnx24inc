"""
Generates the BNX 24 logo SVGs from outlined Inter glyphs (SIL OFL 1.1).
One-time asset build; the outputs are committed. Re-run only to change the logo:

  python3 -m venv .venv && .venv/bin/pip install fonttools brotli
  .venv/bin/python scripts/brand/generate_logos.py
"""
import json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "src/fonts/inter-latin-wght.woff2"

spec = {
    "bnx": {"text": "BNX", "wght": 650, "size": 28, "tracking_em": -0.01},
    "n24": {"text": "24", "wght": 650, "size": 28, "tracking_em": -0.01},
    "inc": {"text": "INC.", "wght": 550, "size": 10, "tracking_em": 0.14},
}
raw = subprocess.check_output(
    [sys.executable, str(Path(__file__).with_name("outline_glyphs.py")), str(FONT), json.dumps(spec)]
)
g = json.loads(raw)

NAVY, INK_ON_DARK = "#0B1F33", "#F8F6F1"
TEAL, TEAL_ON_DARK = "#0E6B64", "#6FCFC2"
SLATE, SLATE_ON_DARK = "#5B6875", "#A9B4BF"

# Monogram on a 32-unit grid: a geometric "B" with a teal full stop.
B_PATH = (
    "M6.5 7H15.5A4.5 4.5 0 0 1 15.5 16H16.5A4.5 4.5 0 0 1 16.5 25H6.5Z"
    "M9.5 10H15.5A2.25 2.25 0 0 1 15.5 14.5H9.5Z"
    "M9.5 17.5H16.5A2.25 2.25 0 0 1 16.5 22H9.5Z"
)
STOP = '<rect x="22.5" y="21.5" width="3.5" height="3.5"/>'

def monogram(tile, letter, stop):
    return (
        f'<rect width="32" height="32" rx="7" fill="{tile}"/>'
        f'<path fill="{letter}" fill-rule="evenodd" d="{B_PATH}"/>'
        f'<g fill="{stop}">{STOP}</g>'
    )

X_BNX = 52
X_24 = X_BNX + g["bnx"]["end"] + 7.5
X_RULE = X_24 + g["n24"]["end"] + 9
X_INC = X_RULE + 9
WIDTH = round(X_INC + g["inc"]["end"] + 1, 2)

def wordmark(tile, letter, stop, text, accent, muted, title):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} 40" role="img" aria-labelledby="t">
<title id="t">{title}</title>
<g transform="scale(1.25)">{monogram(tile, letter, stop)}</g>
<path fill="{text}" transform="translate({X_BNX} 30.2)" d="{g["bnx"]["d"]}"/>
<path fill="{accent}" transform="translate({X_24:.2f} 30.2)" d="{g["n24"]["d"]}"/>
<rect x="{X_RULE:.2f}" y="13" width="1" height="15" fill="{muted}"/>
<path fill="{muted}" transform="translate({X_INC:.2f} 24.4)" d="{g["inc"]["d"]}"/>
</svg>
'''

def mono_svg(tile, letter, stop, title):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" role="img" aria-labelledby="t">
<title id="t">{title}</title>
{monogram(tile, letter, stop)}
</svg>
'''

out = ROOT / "public/brand"
out.mkdir(parents=True, exist_ok=True)
(out / "bnx24-logo.svg").write_text(wordmark(NAVY, INK_ON_DARK, TEAL_ON_DARK, NAVY, TEAL, SLATE, "BNX 24 Inc."))
(out / "bnx24-logo-dark.svg").write_text(wordmark(INK_ON_DARK, NAVY, TEAL, INK_ON_DARK, TEAL_ON_DARK, SLATE_ON_DARK, "BNX 24 Inc."))
(out / "bnx24-monogram.svg").write_text(mono_svg(NAVY, INK_ON_DARK, TEAL_ON_DARK, "BNX 24 Inc."))
(out / "bnx24-monogram-dark.svg").write_text(mono_svg(INK_ON_DARK, NAVY, TEAL, "BNX 24 Inc."))
(ROOT / "src/app").mkdir(parents=True, exist_ok=True)
(ROOT / "src/app/icon.svg").write_text(mono_svg(NAVY, INK_ON_DARK, TEAL_ON_DARK, "BNX 24 Inc."))

# Path data for the inline React logo component (inherits currentColor).
ts = f'''// Generated by scripts/brand/generate_logos.py. Do not edit by hand.
export const logoGeometry = {{
  width: {WIDTH},
  monogramB: "{B_PATH}",
  bnx: {{ x: {X_BNX}, d: "{g["bnx"]["d"]}" }},
  n24: {{ x: {X_24:.2f}, d: "{g["n24"]["d"]}" }},
  rule: {{ x: {X_RULE:.2f} }},
  inc: {{ x: {X_INC:.2f}, d: "{g["inc"]["d"]}" }},
}} as const;
'''
(ROOT / "src/components/brand").mkdir(parents=True, exist_ok=True)
(ROOT / "src/components/brand/logo-geometry.ts").write_text(ts)
print("width", WIDTH)
